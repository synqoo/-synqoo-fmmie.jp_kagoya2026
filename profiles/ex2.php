    <div class="card">
        <h2 class="section-title">行動指針</h2>

        <h3 class="subsection-title">1 【法令、規範の遵守】</h3>
        <h3 class="sub-heading">（1）法令順守</h3>
        <p class="content-text">私たちは、法令や社会の規範を守り、社会的良識に基づいて行動します。法令や社会の規範に背く行為が、会社の存亡に直結することを十分に認識します。</p>
        <h3 class="sub-heading">（2）放送法等の遵守</h3>
        <p class="content-text">私たちは、放送事業に携わる者として、放送法等の趣旨を厳粛に受け止め、これを遵守します。</p>
        <h3 class="sub-heading">（3）社内規程の遵守</h3>
        <p class="content-text">私たちは、「放送基準」等、番組制作に関する社内規範や就業規則等の社内規程を遵守します。</p>
        <h3 class="sub-heading">（4）公平な競争</h3>
        <p class="content-text">私たちは、市場において良識ある行動に努め、関係法令を遵守し、公平・透明・自由な取引を行います。</p>

        <h3 class="subsection-title">2 【聴取者・県民への奉仕】</h3>
        <h3 class="sub-heading">（1）視聴者・県民への奉仕</h3>
        <p class="content-text">私たちは、聴取者が真実を知り、また、楽しみ、満足していただくために奉仕します。</p>
        <h3 class="sub-heading">（2）誠意ある対応</h3>
        <p class="content-text">私たちは、聴取者の意見に誠意を持って対応し、一層の満足と信頼をいただけるよう努めます。</p>

        <h3 class="subsection-title">3 【人権の尊重】</h3>
        <h3 class="sub-heading">（1）差別的扱いの禁止</h3>
        <p class="content-text">私たちは、一人ひとりの人格や個性を尊重します。性別・真情・身体的条件等による差別や嫌がらせを行いません。</p>
        <h3 class="sub-heading">（2）健全な職場環境</h3>
        <p class="content-text">私たちは、不当な差別や嫌がらせのない健全な職場環境を維持します。</p>

        <h3 class="subsection-title">4 【社会の一員としての貢献】</h3>
        <h3 class="sub-heading">（1）地球環境の保全</h3>
        <p class="content-text">私たちは、資源の有効活用や省エネルギーに努め、より良い地球環境を次代に引き継ぎます。</p>
        <h3 class="sub-heading">（2）企業市民としての行動</h3>
        <p class="content-text">私たちは、企業市民としての社会的責任を果たします。</p>
        <h3 class="sub-heading">（3）社会貢献活動</h3>
        <p class="content-text">私たちは、放送等を通じての社会の発展に貢献します。</p>

        <h3 class="subsection-title">5 【取引先との健全な関係の保持】</h3>
        <h3 class="sub-heading">（1）不公正な取引の禁止</h3>
        <p class="content-text">私たちは、取材・番組制作・放送に関係する法人や個人、広告主・広告代理店、その他の取引先に対し、誠実に対応し、節度ある健全な関係を保ちます。</p>
        <h3 class="sub-heading">（2）過剰な贈答・接待の禁止</h3>
        <p class="content-text">私たちは、取材・番組制作・放送に関係する法人や個人、広告主・広告代理店、その他の取引先への過剰な贈答・接待は行いません。</p>
        <h3 class="sub-heading">（3）過剰な贈答・接待の拒否</h3>
        <p class="content-text">私たちは、取材・番組制作・放送に関係する法人や個人、広告主・広告代理店、その他の取引先からの、過剰な贈答・便宜供与・接待は受けません。</p>
        <h3 class="sub-heading">（4）公務員への対応</h3>
        <p class="content-text">私たちは、公務員又はこれに準ずる人への、不正な接待・贈答・便宜供与は行いません。</p>
        <h3 class="sub-heading">（5）反社会的な団体・個人への対応</h3>
        <p class="content-text">私たちは、反社会的な団体・個人に対して、常に毅然とした態度で臨みます。</p>

        <h3 class="subsection-title">6 【誠実で公正な事業活動】</h3>
        <h3 class="sub-heading">（1）企業情報の開示</h3>
        <p class="content-text">私たちは、機密情報や守秘義務のある情報（取材源を含む）を除き、適時・適切な方法で開示します。</p>
        <h3 class="sub-heading">（2）個人情報の管理</h3>
        <p class="content-text">私たちは、個人情報を適正に収集・管理します。</p>
        <h3 class="sub-heading">（3）機密情報の管理</h3>
        <p class="content-text">私たちは、職務上知り得た情報を適正に管理し、退職後も会社の許可なく第三者に対する漏洩や業務以外の目的で使用しません。</p>
        <h3 class="sub-heading">（4）知的財産の管理</h3>
        <p class="content-text">私たちは、知的財産権を尊重し、会社の知的財産を厳格に保全するとともに、他者の知的財産権を侵害しないよう注意を払います。</p>
        <h3 class="sub-heading">（5）会社財産の保護</h3>
        <p class="content-text">私たちは、会社財産は企業価値を生み出す源泉であることを深く認識し、これを大切に扱い、害するような行為は行いません。</p>
        <h3 class="sub-heading">（6）地位利用等の禁止</h3>
        <p class="content-text">私たちは、会社の職務や地位及び財産を私的目的のために使用しません。</p>
        <h3 class="sub-heading">（7）個人的利益相反</h3>
        <p class="content-text">私たちは、私的な利害が会社の利益と相反する場合は、会社の利益を優先します。</p>

        <h3 class="subsection-title">7 【コンプライアンス・ヘルプ対策推進室の設置】</h3>
        <p class="content-text">私たちは、放送に携わる者としての基本的使命と社会的責任を深く認識し、このコンプライアンス憲章に則った業務運営を積極的に確保するとともに、コンプライアンスに関して相談･報告を受け付けるための、コンプライアンス・ヘルプ対策推進室を設置します。</p>
