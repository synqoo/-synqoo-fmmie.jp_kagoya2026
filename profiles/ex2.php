        <p class="content-text">このＦＭ三重・コンプライアンス憲章は、当社の全ての役員・社員・関係者が遵守すべき法令及び企業倫理等にかかる基本的な内部規範を定めています。</p>
        <p class="content-text">当社は、自らこのコンプライアンス憲章を遵守することを宣言するとともに、全ての役員・社員･関係者に対して、このコンプライアンス憲章を遵守し、責任を持った行動を行うよう強く求めていきます。</p>
