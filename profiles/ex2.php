        <p class="content-text">当社は、使命であるラジオ放送を通じて、放送文化を創造し、聴取者の信頼を得て積極的に社会の利益と発展に貢献することで、将来にわたる持続的な発展が約束されるものです。</p>
        <p class="content-text">聴取者からの信頼を得て良好な関係を築いていくことは並大抵のことではありませんが、当社の企業活動の全ての過程で誠実な姿勢で臨むという姿勢を基本として、最大の努力を傾注して企業としての社会的責任を果たしていけば、発展への道は自ずから拓かれてくるものと考えています。</p>
        <p class="content-text">企業の社会的責任を具体的に言えば、それは法律やその他の社会規範を守る「法令遵守」、情報公開を通じた「経営の透明性の確保」、利害関係人に対する「説明責任の完遂」、不詳事の未然防止やその対応を図る「危機管理」であり、それを確実に果たしていくことです。</p>
