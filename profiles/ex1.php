        <h2 class="section-title">2. 人権尊重の徹底</h2>
        <p class="content-text">日本民間放送連盟の放送基準に準拠した「三重エフエム放送株式会社 放送基準」の前文及び綱領において人権尊重を規定しています。</p>

        <h3 class="subsection-title">前文</h3>
        <p class="content-text">三重エフエム放送株式会社は、地域社会の文化の発展、公共の福祉、産業と経済の繁栄に役立ち、平和な社会の実現に寄与することを使命とする。</p>
        <p class="content-text">我々は、この自覚に基づき、民主主義の精神に従い、基本的人権と世論を尊び、言論および表現の自由を守り、法と秩序を尊重して社会の信頼に応えなければならない。</p>

        <h3 class="subsection-title">綱領</h3>
        <p class="content-text">放送に当たっては、次の点を重視して、番組相互の調和と放送時間に留意するとともに、即時性、普遍性など放送のもつ特性を発揮し内容の充実に努める。</p>
        <ol>
            <li>基本的人権を尊重し、民主主義の育成と確立を図る。</li>
            <li>法と社会秩序を尊重し、国民生活の安定に努める。</li>
            <li>児童および青少年に与える影響を考慮し、新しい世代の健全な育成に努める。</li>
            <li>教育・教養の進展を図り、文化の向上に努める。</li>
            <li>社会生活に役立つ正しい情報と健全な娯楽を提供し、生活内容を豊かにするように努める。</li>
            <li>広告は、真実を伝え、聴取者に利益をもたらすように努める。</li>
        </ol>
    </div>

    <div class="card">
        <h2 class="section-title">3. 法令や社会規範の遵守</h2>
        <p class="content-text">日本民間放送連盟の放送基準に準拠した「三重エフエム放送株式会社 放送基準」を策定し、全ての放送番組・広告に適用しています。</p>
        <p class="content-text">個人情報保護規程、情報セキュリティ規程等を策定し、自社が保持する情報を厳格に管理・徹底しています。</p>
        <p class="content-text">ＦＭ三重・コンプライアンス憲章を定め、全ての役員・職員・関係者が法令及び企業倫理等を遵守し、責任を持った行動を行うことを強く求めて行きます。</p>
        <p class="content-text">ＦＭ三重・コンプライアンス憲章に基づき、ＦＭ三重・コンプライアンス・ヘルプ対策推進室を設置し、積極的にコンプライアンス精神の高揚を図るとともに、公平な立場でコンプライアンスに関する相談･報告等を受け、それらへの的確な対応を図ることとしています。</p>
    </div>

